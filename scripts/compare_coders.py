"""Compare any number of checked hand-ins (run once every coder has handed in).

Usage:  python3 scripts/compare_coders.py comparison.md <hand-in folder> <hand-in folder> ...
Each folder needs a codes.tsv from check_handin.py. The folder name is the coder's label.
Writes comparison.md (tables only, no ad text) and disagreements.tsv next to it (quotes the lines: keep private).

Each line gets one label per coder for the headline numbers: its primary facet, or OUT when the coder called it
not about the job, or SIT- for a setting with no facet. That way every coder labels every line.
"""
import csv, itertools, os, sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kitlib


def label(r):
    if r["mode"] == "OUT":
        return "OUT"
    return "SIT-" if r["facet"] == "-" else r["facet"]


def facets_of(r):
    return {f for f in (r["facet"], r["facet2"]) if f and f != "-"}


def cohen(pairs):
    n = len(pairs)
    if not n:
        return None, None
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[k] * cb[k] for k in ca) / n / n
    return (None if pe == 1 else (po - pe) / (1 - pe)), po


def fleiss(rows):
    """rows: one list of labels per line (one label per coder). Returns kappa or None."""
    rows = [r for r in rows if len(r) >= 2]
    if not rows:
        return None
    m = len(rows[0])
    cats = sorted({x for r in rows for x in r})
    p_i, tot = [], Counter()
    for r in rows:
        c = Counter(r)
        tot.update(c)
        p_i.append((sum(v * v for v in c.values()) - m) / (m * (m - 1)))
    pbar = sum(p_i) / len(rows)
    pe = sum((tot[k] / (len(rows) * m)) ** 2 for k in cats)
    return None if pe == 1 else (pbar - pe) / (1 - pe)


def fmt(x, pct=False):
    if x is None:
        return "n/a"
    return f"{100 * x:.0f}%" if pct else f"{x:.2f}"


def main():
    out, folders = sys.argv[1], sys.argv[2:]
    posts = kitlib.load_lines()
    order = kitlib.all_items(posts)
    text = {l["item"]: l["text"] for p in posts for l in p["lines"]}
    coders = {}
    for f in folders:
        codes = kitlib.load_codes(os.path.join(f, "codes.tsv"))
        missing = [i for i in order if i not in codes]
        if missing:
            raise SystemExit(f"{f}: {len(missing)} lines not coded; run check_handin.py first")
        coders[os.path.basename(os.path.abspath(f))] = codes
    names = list(coders)
    o = ["# Round-2 comparison (generated by scripts/compare_coders.py)\n",
         f"{len(names)} coders, {len(order)} lines in {len(posts)} postings. Kappa corrects for chance: 1 is perfect, "
         "0 is chance; under 0.40 poor, 0.40 to 0.60 moderate, 0.60 to 0.80 substantial, over 0.80 near perfect.\n"]

    o.append("## All coders together (Fleiss' kappa)\n")
    o.append("| Question | Kappa |")
    o.append("|---|---|")
    o.append(f"| Line label (primary facet, OUT, or setting with no facet) | "
             f"{fmt(fleiss([[label(coders[c][i]) for c in names] for i in order]))} |")
    o.append(f"| Mode | {fmt(fleiss([[coders[c][i]['mode'] for c in names] for i in order]))} |")
    for f in kitlib.FACETS:
        o.append(f"| {kitlib.NAMES[f]} on the line at all (primary or second) | "
                 f"{fmt(fleiss([[f in facets_of(coders[c][i]) for c in names] for i in order]))} |")
    o.append("")

    o.append("## Pairs: agreement on the line label (kappa, then % agreement)\n")
    o.append("| | " + " | ".join(names) + " |")
    o.append("|---|" + "---|" * len(names))
    for a in names:
        cells = []
        for b in names:
            if a == b:
                cells.append("")
                continue
            k, po = cohen([(label(coders[a][i]), label(coders[b][i])) for i in order])
            cells.append(f"{fmt(k)} ({fmt(po, True)})")
        o.append(f"| {a} | " + " | ".join(cells) + " |")
    o.append("")

    o.append("## What each coder found\n")
    o.append("Job aspects are lines not coded OUT. Facet counts are primary [primary or second].\n")
    o.append("| | " + " | ".join(names) + " |")
    o.append("|---|" + "---|" * len(names))
    asp = {c: [i for i in order if coders[c][i]["mode"] != "OUT"] for c in names}
    o.append("| Job aspects | " + " | ".join(str(len(asp[c])) for c in names) + " |")
    for m in kitlib.MODES:
        o.append(f"| Mode {m} | " + " | ".join(str(sum(coders[c][i]["mode"] == m for i in order)) for c in names) + " |")
    for f in kitlib.FACETS:
        o.append(f"| {kitlib.NAMES[f]} | " + " | ".join(
            f"{sum(coders[c][i]['facet'] == f for i in asp[c])} [{sum(f in facets_of(coders[c][i]) for i in asp[c])}]"
            for c in names) + " |")
    o.append("| Upper facets as primary | " + " | ".join(
        str(sum(coders[c][i]["facet"] in kitlib.UPPER for i in asp[c])) for c in names) + " |")
    o.append("| Low-confidence aspects | " + " | ".join(
        str(sum(coders[c][i]["conf"] == "L" for i in asp[c])) for c in names) + " |")
    o.append("")

    o.append("## Upper facets per posting (how many of the five appear on any job aspect)\n")
    o.append("| Posting | " + " | ".join(names) + " |")
    o.append("|---|" + "---|" * len(names))
    for p in posts:
        ids = [l["item"] for l in p["lines"]]
        o.append(f"| {p['posting']} {p['title']} ({p['company']}) | " + " | ".join(
            str(len({f for i in ids if coders[c][i]['mode'] != 'OUT' for f in facets_of(coders[c][i])} & set(kitlib.UPPER)))
            for c in names) + " |")
    o.append("")
    open(out, "w").write("\n".join(o))

    dis = os.path.join(os.path.dirname(os.path.abspath(out)), "disagreements.tsv")
    with open(dis, "w", newline="") as fh:
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["item", "labels_agree"] + [f"{c}" for c in names] + [f"{c}_note" for c in names] + ["line"])
        for i in order:
            labs = [label(coders[c][i]) for c in names]
            if len(set(labs)) > 1 or len({coders[c][i]["mode"] for c in names}) > 1:
                cells = [f"{coders[c][i]['mode']}:{'/'.join(x for x in (coders[c][i]['facet'], coders[c][i]['facet2']) if x)}:"
                         f"{coders[c][i]['conf']}" for c in names]
                w.writerow([i, max(Counter(labs).values())] + cells + [coders[c][i]["note"] for c in names] + [text[i]])
    print("wrote", out, "and", dis)


if __name__ == "__main__":
    main()
